CREATE TABLE IF NOT EXISTS app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_session (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    token_hash VARCHAR(100) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id VARCHAR(32) PRIMARY KEY,
    supplier_name VARCHAR(150) NOT NULL,
    product_name VARCHAR(150) NOT NULL,
    category VARCHAR(80) NOT NULL,
    buying_price NUMERIC(14, 2) NOT NULL CHECK (buying_price >= 0),
    contact VARCHAR(80) NOT NULL,
    email VARCHAR(255),
    supplier_type VARCHAR(32) NOT NULL CHECK (supplier_type IN ('Taking return', 'Not taking return')),
    on_the_way INTEGER NOT NULL DEFAULT 0 CHECK (on_the_way >= 0),
    image_url VARCHAR(1024),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    product_id VARCHAR(64) PRIMARY KEY,
    product_name VARCHAR(180) NOT NULL,
    category VARCHAR(80) NOT NULL,
    buying_price NUMERIC(14, 2) NOT NULL CHECK (buying_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    unit VARCHAR(24) NOT NULL,
    expiry_date DATE NOT NULL,
    threshold INTEGER NOT NULL CHECK (threshold >= 0),
    supplier_id VARCHAR(32) REFERENCES suppliers(supplier_id) ON DELETE SET NULL,
    image_url VARCHAR(1024),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS stock_locations (
    stock_location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(64) NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    location_name VARCHAR(120) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_stock_product_location UNIQUE (product_id, location_name)
);

CREATE TABLE IF NOT EXISTS inventory_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(64) NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    event_type VARCHAR(24) NOT NULL CHECK (event_type IN ('INITIAL', 'PURCHASE', 'ADJUSTMENT')),
    quantity_change INTEGER NOT NULL,
    description VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_products_name ON products(product_name);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_expiry ON products(expiry_date);
CREATE INDEX IF NOT EXISTS idx_suppliers_name ON suppliers(supplier_name);
CREATE INDEX IF NOT EXISTS idx_inventory_events_product ON inventory_events(product_id, created_at);
CREATE INDEX IF NOT EXISTS idx_user_session_expiry ON user_session(expires_at);
